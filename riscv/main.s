    li a1, 4608                  # Number of elements in the input image
    call relu                    # Call relu function
    

    j _finish                     # Jump to _finish

_finish:
    li x3, 0xd0580000
    addi x5, x0, 0xff
    sb x5, 0(x3)
    beq x0, x0, _finish
.rept 100
    nop
